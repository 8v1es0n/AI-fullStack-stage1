"""
1. 需求：根据用户输入的年份，判断这一年是闰年还是平年。
  1. 非整百年份，且能被4整除的年份是闰年
  2. 必须能被400整除才是闰年
"""
#  1. 键盘录入年份
year = input("请示入一个年份: ")
if (year % 100 != 0 and year % 4 == 0) or (year % 400 == 0):
    print(f"{year}是闰年")
else:
    print(f"{year}是平年")