# 单路if格式
# if 要判断的条件:
#     条件成立时, 要执行的操作

"""
    需求：结合前面学习的输入输出及if条件判断的知识，完成B站登录功能的实现（正确账号和密码为 18888888888/666888）。
    1. 提示用户输入账号和密码。
    2. 判断账号和密码是否正确，如果账号和密码都正确，则登录成功，进入B站首页。
    3. 如果账号和密码有一个错误，则登录失败，提示错误信息。
"""

# 输入用户信息
username1 = input("请输入用户名: ")
fwd1 = input("请输入密码: ")

# 登陆状态判断
if username1 == 18888888888 and fwd1 == "666888":
    print("登录成功!")

if username1 != 18888888888 and fwd1 != "666888":
    print("登录失败!")


