# 列表格式:  列表名 = [元素1 , 元素2 , 元素3......元素n]
#  特点: 1. 可以存储多种类型  2. 有序   3. 可重复  4. 可修改

list01 = ["关羽", "张飞", "赵云", "黄忠", "马超", "赵云", "赵云"]

# 根据索引获取元素
print(list01[3])

# 修改元素
list01[-2] = "刘姥姥" #负索引

# 删除元素
del list01[-1]

# 只写列表名,就是打印所有元素
print(list01)
print("----------------------")

# 列表的切片
# 格式:   列表名[开始索引: 结束索引: 步长]
list02 = list01[2: 5: 1]
print(list02)
list03 = list01[: 5: 2]
print(list03)
list04 = list01[: : 3]
print(list04)
list04 = list01[: : -2]
print(list04)