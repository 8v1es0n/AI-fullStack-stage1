"""
08 - 赋值运算符

1. 基本赋值：=
       把右边的值存进左边的变量，注意方向不能反（a = 10 读作"把 10 赋给 a"）

2. 扩展赋值：+=  -=  *=  /=  //=  %=  **=
       是"先运算，再把结果存回自己"的简写，等价于 a = a + 20

3. Python 没有 ++ 和 -- 运算符（那是 Java/C 的写法）
       想让变量加 1 就用 a += 1，减 1 就用 a -= 1
"""

# 基本的赋值运算符 : =
a = 10  # 把10赋值给了变量a

# 扩展的赋值运算符 : +=  -=  *=  /=   //=   %=  **=
# 运算规则 : 把符号两边的数据做运算符 , 再把运算的结果赋值给符号左边的变量
a += 20  # a = a + 20
print(a)  # 10 + 20 = 30

x = 2
x **= 3  # x = x ** 3
print(x)  # 2 的 3 次方 = 8

# python不存在 ++  --  , 如何解决?
y = 10
y -= 1  # 等价于 y = y - 1，结果是 9。想加 1 就写 y += 1
