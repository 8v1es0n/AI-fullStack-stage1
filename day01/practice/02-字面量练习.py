# 字面量练习
# 1-数值类型
print(100)
print(-5)
print(1.5)
print("-------------------")

# 字符串类型
print('Hello')
print("World")
print("""你好!""")
print("-------------------")

# 布尔类型
print(True)
print(False)
print("-------------------")

# 空值类型
print(None)
print("-------------------")

# 注意:布尔类型在数值运算时,会自动转换,True为1,False为0
print(1 + True)
print(1 + False)
