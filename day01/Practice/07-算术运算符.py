# 算术运算符:  +  -  *  /  //  %  **
print(6 + 4)  # 10
print(6 - 4)  # 2
print(6 * 4)  # 24
# / 可以取到小鼠
print(6 / 4)  # 1.5
# 只能取到整数
print(6 // 4)  # 1
#  两数相除 再取余数
print(6 % 4)  # 2
#  2 的 4 次幂
print(2 ** 4)  # 16


